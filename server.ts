// AI Generator API: Generate or Refactor Liquid Section
app.post("/api/gemini/generate-section", async (req, res) => {
  try {
    const { prompt, sectionType, existingCode, mode } = req.body;

    const systemInstruction = `You are a master Shopify Liquid & Storefront OS 2.0 developer building code for the "E-sellers Pro" theme (Developer: E-sellers, Email: info@e-sellers.net).
Generate highly performant, semantic, accessible, and valid Shopify Liquid OS 2.0 section code.
Each section MUST include:
1. Liquid template code with modern filters (e.g. image_url, render, | t, default).
2. Embedded CSS or inline Liquid styles wrapped in {% style %}...{% endstyle %} using clean CSS variables.
3. Embedded JavaScript if needed wrapped in {% javascript %}...{% endjavascript %}.
4. Valid JSON Schema wrapped in {% schema %}{...}{% endschema %} with:
   - "name", "tag": "section", "class", "settings" (with type, id, label, default)
   - "blocks" (if relevant for repetitive items like slides, features, badges)
   - "presets": [{ "name": "...", "category": "..." }]
5. Header comments identifying "Theme: E-sellers Pro | Developer: E-sellers (info@e-sellers.net)".

Return ONLY a JSON object with keys:
- "liquidCode": string (the complete .liquid section code)
- "sectionName": string (e.g. "e-sellers-hero-banner.liquid")
- "description": string
- "settingsCount": number
- "blocksCount": number`;

    const userPrompt = mode === "refactor"
      ? `Refactor the following code to adhere strictly to Shopify OS 2.0 best practices and E-sellers Pro theme standards:\n\n${existingCode}\n\nAdditional instructions: ${prompt}`
      : `Create a new Shopify OS 2.0 Liquid section for theme "E-sellers Pro". Section Type/Idea: ${sectionType || "Custom Section"}.\nInstructions: ${prompt}`;

    const response = await ai.models.generateContent({
      model: "gemini-3.6-flash",
      contents: userPrompt,
      config: {
        systemInstruction,
        responseMimeType: "application/json",
      },
    });

    const resultText = response.text || "{}";
    const data = JSON.parse(resultText);
    res.json({ success: true, data });
  } catch (error: any) {
    console.error("Error in generate-section:", error);
    res.status(500).json({ success: false, error: error.message || "Failed to generate Liquid section" });
  }
});

